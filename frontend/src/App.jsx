        <div className="sat-brand">
          <span className="sat-seal">悟</span>
          <div>
            <div className="sat-title">Residue Compare</div>
            <div className="sat-sub">Single-compound δ¹³C · British &amp; Irish Neolithic</div>
          </div>
        </div>
        {isIllustrative && (
          <span className="sat-flag"><AlertTriangle size={13} /> Illustrative data — run pipeline/05_export.py</span>
        )}
