// ─── Corpus loading ───────────────────────────────────────────────────────────
function useCorpus() {
  const [corpus, setCorpus] = useState(null);  // null = loading; [] = loaded (may be empty)
  const [loadError, setLoadError] = useState(null);

  useEffect(() => {
    fetch("/corpus.json")
      .then(r => {
        if (!r.ok) throw new Error(`HTTP ${r.status}`);
        return r.json();
      })
      .then(data => setCorpus(data))
      .catch(err => {
        console.warn("corpus.json not found — showing illustrative data:", err.message);
        setLoadError(err.message);
        setCorpus({ meta: { record_count: 0, sources: [] }, records: [] });
      });
  }, []);

  return { corpus, loadError };
}

